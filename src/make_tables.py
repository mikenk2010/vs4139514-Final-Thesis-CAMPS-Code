TABLE_E2_TEMPLATE = r"""% AUTO-GENERATED by make_tables.py -- do not edit by hand.
\begin{table}[htbp]
\centering
\caption[E2: ablation over panel size and adjudicator]{Experiment E2:
ablation over panel size $k$ and the meta-adjudicator (model:
%%MODEL%%), with 95\% bootstrap confidence intervals.}
\label{tab:e2-ablation}
\small
\begin{tabular}{lccc}
\hline
Configuration & QWK\textsubscript{SEA} & QWK\textsubscript{native} & Gap \\
\hline
%%BODY%%
\hline
\end{tabular}
\end{table}
"""


def table_e2(df: pd.DataFrame, out: Path, model: str) -> None:
    from metrics import consensus_and_bds
    truth = (df.drop_duplicates("essay_id")
               .set_index("essay_id").cefr.map(BAND_MAP))
    labels = {"baseline": "Baseline ($k{=}1$)",
              "camps_k3": "CAMPS $k{=}3$",
              "camps_k5": "CAMPS $k{=}5$",
              "camps_k5_adj": "CAMPS $k{=}5$ + adjudicator"}
    rows = []
    sub_all = df[df.model == model]
    for cond in ["baseline", "camps_k3", "camps_k5", "camps_k5_adj"]:
        sub = sub_all[sub_all.condition == cond]
        if sub.empty:
            continue
        if cond == "camps_k5_adj":
            # the adjudicated score is the aggregate for this condition
            from metrics import adjudicated_scores
            agg = (adjudicated_scores(sub)
                   .rename(columns={"adjudicated": "consensus"}))
            if agg.empty:
                continue
        else:
            agg = consensus_and_bds(sub)
        cells = {}
        for cohort in ("sea", "native"):
            g = agg[agg.cohort == cohort]
            if g.empty:
                continue
            h = truth.loc[g.essay_id].to_numpy()
            m = np.rint(g.consensus.to_numpy())
            cells[cohort] = bootstrap_ci(h, m)
        if {"sea", "native"} <= cells.keys():
            gap = cells["native"][0] - cells["sea"][0]
            rows.append(f"{labels[cond]} & {fmt_ci(*cells['sea'])} & "
                        f"{fmt_ci(*cells['native'])} & {gap:.3f} \\\\")
    out.write_text(TABLE_E2_TEMPLATE.replace("%%BODY%%", "\n".join(rows))
                   .replace("%%MODEL%%", model))
    print(f"wrote {out} ({len(rows)} rows)")


TABLE_E3_TEMPLATE = r"""% AUTO-GENERATED by make_tables.py -- do not edit by hand.
\begin{table}[htbp]
\centering
\caption[E3: BDS detection performance]{Experiment E3: BDS detection
performance on the held-out GRA split (model: %%MODEL%%).}
\label{tab:e3-bds}
\small
\begin{tabular}{lc}
\hline
Quantity & Value \\
\hline
%%BODY%%
\hline
\end{tabular}
\end{table}
"""


def table_e3(df: pd.DataFrame, gra_dispersion: "pd.Series | None",
             out: Path, model: str, seed: int = 4139514) -> None:
    """Calibrate tau on half the GRA set, evaluate on the other half.

    'Contested' ground truth = top-quartile human rating dispersion.
    Requires gra_dispersion indexed by essay_id (from the GRA xlsx).
    """
    from metrics import consensus_and_bds, roc_calibrate
    from sklearn.metrics import roc_auc_score
    sub = df[(df.model == model) & (df.cohort == "gra")]
    if sub.empty or gra_dispersion is None:
        out.write_text("% E3 pending: no GRA scoring log or dispersion data\n")
        print("E3 table: pending (no data)")
        return
    agg = consensus_and_bds(sub).set_index("essay_id")
    common = agg.index.intersection(gra_dispersion.index)
    bds = agg.loc[common, "bds"].to_numpy()
    disp = gra_dispersion.loc[common].to_numpy()
    contested = (disp >= np.quantile(disp, 0.75)).astype(int)
    rng = np.random.default_rng(seed)
    idx = rng.permutation(len(common))
    half = len(idx) // 2
    cal, ev = idx[:half], idx[half:]
    tau, _ = roc_calibrate(bds[cal], contested[cal])
    pred = (bds[ev] >= tau).astype(int)
    tp = int(((pred == 1) & (contested[ev] == 1)).sum())
    fp = int(((pred == 1) & (contested[ev] == 0)).sum())
    fn = int(((pred == 0) & (contested[ev] == 1)).sum())
    tn = int(((pred == 0) & (contested[ev] == 0)).sum())
    sens = tp / (tp + fn) if tp + fn else float("nan")
    fpr = fp / (fp + tn) if fp + tn else float("nan")
    auc_ev = roc_auc_score(contested[ev], bds[ev])
    r = np.corrcoef(bds, disp)[0, 1]
    body = "\n".join([
        f"Calibrated threshold $\\tau$ & {tau:.3f} \\\\",
        f"Sensitivity (held-out, $n$={len(ev)}) & {sens:.3f} \\\\",
        f"False-positive rate (held-out) & {fpr:.3f} \\\\",
        f"Area under ROC curve (held-out) & {auc_ev:.3f} \\\\",
        f"Correlation of BDS with human dispersion & {r:.3f} \\\\",
    ])
    out.write_text(TABLE_E3_TEMPLATE.replace("%%BODY%%", body)
                   .replace("%%MODEL%%", model))
    print(f"wrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/E1")
    ap.add_argument("--tables-dir",
                    default="../s4139514-Final-Thesis-CAMPS/tables")
    ap.add_argument("--experiment", default="E1", choices=["E1", "E2", "E3"])
    ap.add_argument("--model", default="gpt-4o",
                    help="model for E2/E3 tables")
    ap.add_argument("--gra-dispersion", default="results/gra_dispersion.csv",
                    help="CSV with essay_id,dispersion from the GRA xlsx")
    args = ap.parse_args()
    log = Path(args.results) / "scores.jsonl"
    if not log.exists():
        raise SystemExit(f"No log at {log} - run the experiment first.")
    df = pd.DataFrame([json.loads(l) for l in
                       log.read_text().splitlines()])
    tables = Path(args.tables_dir)
    if args.experiment == "E1":
        table_e1(df, tables / "table_e1_qwk.tex")
    elif args.experiment == "E2":
        table_e2(df, tables / "table_e2_ablation.tex", args.model)
    elif args.experiment == "E3":
        disp = None
        if args.gra_dispersion and Path(args.gra_dispersion).exists():
            d = pd.read_csv(args.gra_dispersion)
            disp = d.set_index("essay_id")["dispersion"]
        table_e3(df, disp, tables / "table_e3_bds.tex", args.model)


if __name__ == "__main__":
    main()

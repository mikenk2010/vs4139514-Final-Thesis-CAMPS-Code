"""Generate the Chapter 4 LaTeX tables from experiment logs.

Reads results/<EXP>/scores.jsonl and overwrites the table files under
RMIT_Thesis_Bao-Nguyen/tables/, so recompiling the thesis picks up real
numbers with no hand editing (reproducibility convention: no statistic
is computed by hand).

Until an experiment has run, the placeholder tables (dashes) remain.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from metrics import bootstrap_ci, consensus_and_bds

BAND_MAP = {"A2_0": 1, "B1_1": 2, "B1_2": 3, "B2_0": 4}  # CEFR -> ordinal


def fmt_ci(point: float, lo: float, hi: float) -> str:
    return f"{point:.3f} [{lo:.3f}, {hi:.3f}]"


def table_e1(df: pd.DataFrame, out: Path) -> None:
    agg = consensus_and_bds(df)
    truth = (df.drop_duplicates("essay_id")
               .set_index("essay_id").cefr.map(BAND_MAP))
    rows = []
    for (model, cond), g in agg.groupby(["model", "condition"]):
        cells = {}
        for cohort in ("sea", "native"):
            gc = g[g.cohort == cohort]
            if gc.empty:
                continue
            h = truth.loc[gc.essay_id].to_numpy()
            m = np.rint(gc.consensus.to_numpy())
            cells[cohort] = bootstrap_ci(h, m)
        if {"sea", "native"} <= cells.keys():
            gap = cells["native"][0] - cells["sea"][0]
            rows.append(
                f"{model} & {cond} & {fmt_ci(*cells['sea'])} & "
                f"{fmt_ci(*cells['native'])} & {gap:.3f} \\\\")
    body = "\n".join(rows)
    out.write_text(TABLE_E1_TEMPLATE.replace("%%BODY%%", body))
    print(f"wrote {out} ({len(rows)} rows)")


TABLE_E1_TEMPLATE = r"""% AUTO-GENERATED by make_tables.py -- do not edit by hand.
\begin{table}[htbp]
\centering
\caption[E1: per-model QWK by cohort]{Experiment E1: Quadratic Weighted
Kappa by model, condition, and cohort, with 95\% bootstrap confidence
intervals ($n$ per cohort as in Section~3.4); gap $=
\kappa_w^{\mathrm{native}} - \kappa_w^{\mathrm{SEA}}$.}
\label{tab:e1-qwk}
\small
\begin{tabular}{llccc}
\hline
Model & Condition & QWK\textsubscript{SEA} [95\% CI] &
QWK\textsubscript{native} [95\% CI] & Gap \\
\hline
%%BODY%%
\hline
\end{tabular}
\end{table}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/E1")
    ap.add_argument("--tables-dir",
                    default="../s4139514-Final-Thesis-CAMPS/tables")
    args = ap.parse_args()
    log = Path(args.results) / "scores.jsonl"
    if not log.exists():
        raise SystemExit(f"No log at {log} - run the experiment first.")
    df = pd.DataFrame([json.loads(l) for l in
                       log.read_text().splitlines()])
    table_e1(df, Path(args.tables_dir) / "table_e1_qwk.tex")


if __name__ == "__main__":
    main()

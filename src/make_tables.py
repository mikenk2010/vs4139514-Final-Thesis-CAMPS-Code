def table_e2(df: pd.DataFrame, out: Path, model: str) -> None:
    from metrics import consensus_and_bds
    truth = (df.drop_duplicates("essay_id")
               .set_index("essay_id").cefr.map(BAND_MAP))
    labels = {"baseline": "Baseline ($k{=}1$)",
              "camps_k3": "CAMPS $k{=}3$",
              "camps_k5": "CAMPS $k{=}5$",
              "camps_k5_adj": "CAMPS $k{=}5$ + adjudicator"}
    model_label = {"gpt-4o": "GPT-4o", "claude-sonnet": "Claude Sonnet"}
    rows = []
    for mdl in [m for m in model_label if m in set(df.model)]:
        sub_all = df[df.model == mdl]
        for cond in ["baseline", "camps_k3", "camps_k5", "camps_k5_adj"]:
            sub = sub_all[sub_all.condition == cond]
            if sub.empty:
                continue
            if cond == "camps_k5_adj":
                # the adjudicated score is the aggregate for this condition
                from metrics import adjudicated_scores
                agg = (adjudicated_scores(sub)
                       .rename(columns={"adjudicated": "consensus"}))
                if agg.empty:
                    continue
            else:
                agg = consensus_and_bds(sub)
            sea = agg[agg.cohort == "sea"].consensus.to_numpy()
            nat = agg[agg.cohort == "native"].consensus.to_numpy()
            if len(sea) < 100 or len(nat) < 100:
                if len(sea) or len(nat):
                    print(f"  SKIP partial cell {mdl}/{cond}: "
                          f"sea={len(sea)} nat={len(nat)}")
                continue
            point, lo, hi = gap_ci(sea, nat)
            rows.append(
                f"{model_label[mdl]} & {labels[cond]} & {sea.mean():.2f} & "
                f"{nat.mean():.2f} & "
                f"{point:.2f} [{lo:.2f}, {hi:.2f}] \\\\")
    out.write_text(TABLE_E2_TEMPLATE.replace("%%BODY%%", "\n".join(rows)))
    print(f"wrote {out} ({len(rows)} rows)")



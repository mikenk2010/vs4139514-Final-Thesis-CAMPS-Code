def table_e3(df: pd.DataFrame, gra_dispersion: "pd.Series | None",
             out: Path, model: str, seed: int = 4139514) -> None:
    """Calibrate tau on half the GRA set, evaluate on the other half.

    'Contested' ground truth = top-quartile human rating dispersion.
    Requires gra_dispersion indexed by essay_id (from the GRA xlsx).
    """
    from metrics import consensus_and_bds, roc_calibrate
    from sklearn.metrics import roc_auc_score
    if gra_dispersion is None:
        out.write_text("% E3 pending: no dispersion data\n")
        print("E3 table: pending (no data)")
        return
    cols = {}
    n_ev = None
    for mdl in ["gpt-4o", "claude-sonnet"]:
        sub = df[(df.model == mdl) & (df.cohort == "gra")]
        if sub.empty:
            continue
        agg = consensus_and_bds(sub).set_index("essay_id")
        common = agg.index.intersection(gra_dispersion.index)
        bds = agg.loc[common, "bds"].to_numpy()
        disp = gra_dispersion.loc[common].to_numpy()
        contested = (disp >= np.quantile(disp, 0.75)).astype(int)
        rng = np.random.default_rng(seed)
        idx = rng.permutation(len(common))
        half = len(idx) // 2
        cal, ev = idx[:half], idx[half:]
        tau, _ = roc_calibrate(bds[cal], contested[cal])
        pred = (bds[ev] >= tau).astype(int)
        tp = int(((pred == 1) & (contested[ev] == 1)).sum())
        fp = int(((pred == 1) & (contested[ev] == 0)).sum())
        fn = int(((pred == 0) & (contested[ev] == 1)).sum())
        tn = int(((pred == 0) & (contested[ev] == 0)).sum())
        sens = tp / (tp + fn) if tp + fn else float("nan")
        fpr = fp / (fp + tn) if fp + tn else float("nan")
        cols[mdl] = [f"{tau:.2f}", f"{sens:.3f}", f"{fpr:.3f}",
                     f"{roc_auc_score(contested[ev], bds[ev]):.3f}",
                     f"{np.corrcoef(bds, disp)[0, 1]:.3f}"]
        n_ev = len(ev)
    if not cols:
        out.write_text("% E3 pending: no GRA scoring log\n")
        print("E3 table: pending (no data)")
        return
    names = [f"Calibrated threshold $\\tau$",
             f"Sensitivity (held-out, $n$={n_ev})",
             "False-positive rate (held-out)",
             "Area under ROC curve (held-out)",
             "Correlation of BDS with human dispersion"]
    blank = ["--"] * 5
    g, c = cols.get("gpt-4o", blank), cols.get("claude-sonnet", blank)
    body = "\n".join(f"{n} & {a} & {b} \\\\"
                     for n, a, b in zip(names, g, c))
    out.write_text(TABLE_E3_TEMPLATE.replace("%%BODY%%", body))
    print(f"wrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/E1")
    ap.add_argument("--tables-dir",
                    default="../s4139514-Final-Thesis-CAMPS/tables")
    ap.add_argument("--experiment", default="E1", choices=["E1", "E2", "E3"])
    ap.add_argument("--model", default="gpt-4o",
                    help="model for E2/E3 tables")
    ap.add_argument("--gra-dispersion", default="results/gra_dispersion.csv",
                    help="CSV with essay_id,dispersion from the GRA xlsx")
    args = ap.parse_args()
    log = Path(args.results) / "scores.jsonl"
    if not log.exists():
        raise SystemExit(f"No log at {log} - run the experiment first.")
    df = pd.DataFrame([json.loads(l) for l in
                       log.read_text().splitlines()])
    if args.experiment == "E2":
        # the E2 ablation table includes the k=1/k=3 rows for comparison
        e1 = Path("results/E1/scores.jsonl")
        if e1.exists():
            df = pd.concat([df, pd.DataFrame(
                [json.loads(l) for l in e1.read_text().splitlines()])],
                ignore_index=True)
    tables = Path(args.tables_dir)
    if args.experiment == "E1":
        table_e1(df, tables / "table_e1_qwk.tex")
    elif args.experiment == "E2":
        table_e2(df, tables / "table_e2_ablation.tex", args.model)
    elif args.experiment == "E3":
        disp = None
        if args.gra_dispersion and Path(args.gra_dispersion).exists():
            d = pd.read_csv(args.gra_dispersion)
            disp = d.set_index("essay_id")["dispersion"]
        table_e3(df, disp, tables / "table_e3_bds.tex", args.model)


if __name__ == "__main__":
    main()

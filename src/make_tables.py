"""Generate the Chapter 4 LaTeX tables from experiment logs.

Reads results/<EXP>/scores.jsonl and overwrites the table files under
RMIT_Thesis_Bao-Nguyen/tables/, so recompiling the thesis picks up real
numbers with no hand editing (reproducibility convention: no statistic
is computed by hand).

Until an experiment has run, the placeholder tables (dashes) remain.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from metrics import bootstrap_ci, consensus_and_bds

BAND_MAP = {"A2_0": 1, "B1_1": 2, "B1_2": 3, "B2_0": 4}  # CEFR -> ordinal


def fmt_ci(point: float, lo: float, hi: float) -> str:
    return f"{point:.3f} [{lo:.3f}, {hi:.3f}]"


def gap_ci(sea, nat, n_boot=10_000, seed=4139514):
    """Native-minus-SEA mean score gap with percentile bootstrap CI."""
    rng = np.random.default_rng(seed)
    point = nat.mean() - sea.mean()
    boots = np.empty(n_boot)
    for b in range(n_boot):
        boots[b] = (rng.choice(nat, len(nat)).mean()
                    - rng.choice(sea, len(sea)).mean())
    lo, hi = np.percentile(boots, [2.5, 97.5])
    return float(point), float(lo), float(hi)


def table_e1(df: pd.DataFrame, out: Path) -> None:
    """Primary E1 table: cohort means and the score gap with CI.

    The native cohort carries no CEFR band, so QWK against bands is
    undefined for it; the primary fairness quantity is the cohort score
    gap on proficiency-matched cohorts, with a bootstrap CI.
    """
    agg = consensus_and_bds(df)
    cond_label = {"baseline": "Baseline", "camps_k3": "CAMPS $k{=}3$",
                  "camps_k5": "CAMPS $k{=}5$",
                  "camps_k5_adj": "CAMPS $k{=}5$+adj."}
    model_label = {"gpt-4o": "GPT-4o", "claude-sonnet": "Claude Sonnet",
                   "gemini-pro": "Gemini Pro", "qwen3-local": "Qwen3 14B",
                   "llama-70b": "Llama 3.3 70B"}
    rows = []
    for (model, cond), g in agg.groupby(["model", "condition"]):
        sea = g[g.cohort == "sea"].consensus.to_numpy()
        nat = g[g.cohort == "native"].consensus.to_numpy()
        if len(sea) == 0 or len(nat) == 0:
            continue
        point, lo, hi = gap_ci(sea, nat)
        model = model_label.get(model, model.replace("_", "\\_"))
        cond = cond_label.get(cond, cond.replace("_", "\\_"))
        rows.append(
            f"{model} & {cond} & {sea.mean():.2f} ($n$={len(sea)}) & "
            f"{nat.mean():.2f} ($n$={len(nat)}) & "
            f"{point:.2f} [{lo:.2f}, {hi:.2f}] \\\\")
    body = "\n".join(rows)
    out.write_text(TABLE_E1_TEMPLATE.replace("%%BODY%%", body))
    print(f"wrote {out} ({len(rows)} rows)")



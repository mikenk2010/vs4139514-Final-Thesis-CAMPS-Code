def thesis_user_prompt(essay: str) -> str:
    """Byte-identical to run_experiment.py so thesis essays hit the cache."""
    return ("Score the following essay. Respond with JSON: "
            '{"score": <band>, "rationale": "<2-3 sentences>"}.\n\n'
            f"ESSAY:\n{essay}")


# ----------------------------------------------------------------- data
@st.cache_data(show_spinner=False)
def load_logs() -> pd.DataFrame:
    frames = []
    for exp in ("E1", "E2", "E3"):
        p = Path(f"results/{exp}/scores.jsonl")
        if p.exists():
            df = pd.DataFrame([json.loads(l) for l in p.read_text().splitlines()])
            df["experiment"] = exp
            frames.append(df)
    return pd.concat(frames, ignore_index=True)


@st.cache_data(show_spinner=False)
def load_manifest(path: str) -> pd.DataFrame:
    return pd.read_csv(path).drop_duplicates("essay_id").set_index("essay_id")


@st.cache_data(show_spinner=False)
def load_gra() -> pd.DataFrame | None:
    p = Path("results/gra_dispersion.csv")
    return pd.read_csv(p).set_index("essay_id") if p.exists() else None


@st.cache_data(show_spinner=False)
def load_summary() -> dict | None:
    p = Path("results/demo_summary.json")
    return json.loads(p.read_text()) if p.exists() else None


def read_essay(cfg: dict, mf: pd.DataFrame, essay_id: str) -> str:
    return (Path(cfg["paths"]["icnale_root"]) / mf.loc[essay_id, "path"]
            ).read_text(encoding="utf-8-sig")


def bds_of(scores: list[float]) -> tuple[float, float]:
    c = sum(scores) / len(scores)
    return c, (sum((s - c) ** 2 for s in scores) / len(scores)) ** 0.5


# ----------------------------------------------------------------- widgets
def score_chart(baseline: float | None, lens_scores: dict[str, float],
                adjudicated: float | None, title: str) -> go.Figure:
    names, vals, cols = [], [], []
    if baseline is not None:
        names.append("Standard grader"); vals.append(baseline)
        cols.append(COLOUR["neutral_single"])
    for a, s in lens_scores.items():
        names.append(LENS[a]); vals.append(s); cols.append(COLOUR[a])
    if adjudicated is not None:
        names.append("Adjudicator"); vals.append(adjudicated)
        cols.append(COLOUR["adjudicator"])
    fig = go.Figure(go.Bar(x=names, y=vals, marker_color=cols,
                           text=[f"{v:.1f}" for v in vals],
                           textposition="outside"))
    if lens_scores:
        c, _ = bds_of(list(lens_scores.values()))
        fig.add_hline(y=c, line_dash="dash", line_color="#444",
                      annotation_text=f"panel consensus {c:.2f}",
                      annotation_position="top left")
    fig.update_yaxes(range=[0, 9.6], title="band (1-9)")
    fig.update_layout(title=title, height=360, margin=dict(t=50, b=10, l=10, r=10),
                      showlegend=False)
    return fig


def verdict_box(bds: float, model: str, k: int) -> None:
    tau = TAU_YOUDEN
    flagged = bds >= tau
    tc = TAU_CONSTRAINED.get(model)
    msg = (f"**BDS {bds:.2f}** vs Youden threshold {tau:.2f} (k = 5, "
           f"thesis Section 4.3) -> **{'would be flagged' if flagged else 'would not be flagged'}** "
           f"for human review.")
    if tc is not None:
        msg += (f" Under the stricter rule H3 specified (calibration false-positive "
                f"rate <= 5%), the threshold is {tc:.2f}: "
                f"{'flagged' if bds >= tc else 'not flagged'}.")
    (st.warning if flagged else st.success)(msg)
    st.caption("Honest note: Experiment 3 found BDS did **not** meet its "
               "90%-sensitivity / 5%-false-positive target against 80 human "
               "raters. It is a candidate review trigger, shown here as the "
               "framework proposes it, not a validated detector."
               + (" BDS from a 3-lens panel takes only four possible values."
                  if k == 3 else ""))


def rationale_panel(rows: pd.DataFrame, order: list[str]) -> None:
    for a in order:
        r = rows[rows.agent == a]
        if r.empty:
            continue
        r = r.iloc[0]
        with st.expander(f"{LENS[a]} - band {r.score:.1f}", expanded=(a in ("western", "sea"))):
            st.write(r.rationale)


